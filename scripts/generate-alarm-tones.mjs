/**
 * Generates the bundled alarm tones shipped in `android/app/src/main/res/raw`.
 *
 * WHY GENERATED AND NOT DOWNLOADED
 *   Every previous tone referenced a `content://settings/system/...` URI. Those
 *   URIs are NOT stable across vendors — on several Android builds the ROM
 *   points them at a silent audio stream, and a `default` channel resolves to a
 *   silent channel when "Default notification sound" is set to None. The result
 *   is exactly what the owner reported: the notification appears, no sound.
 *
 *   A tone that lives in the APK cannot be silenced by a system setting and has
 *   no licensing question: these are synthesised sine/triangle envelopes
 *   generated by this script, not third-party audio.
 *
 * Run: node scripts/generate-alarm-tones.mjs
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const RAW_DIR = resolve(HERE, '..', 'android', 'app', 'src', 'main', 'res', 'raw')
/** Web builds play the same assets through an <audio> element. */
const WEB_DIR = resolve(HERE, '..', 'public', 'tones')

const SAMPLE_RATE = 22050

/** One note: start offset (s), length (s), frequency (Hz), amplitude, wave. */
function tone(id, notes, total) {
  const frames = Math.ceil(total * SAMPLE_RATE)
  const samples = new Float32Array(frames)
  for (const note of notes) {
    const start = Math.floor(note.start * SAMPLE_RATE)
    const length = Math.floor(note.length * SAMPLE_RATE)
    for (let i = 0; i < length; i += 1) {
      const t = i / SAMPLE_RATE
      // Short raised-cosine attack and decay: a click-free envelope.
      const attack = Math.min(1, t / 0.012)
      const release = Math.min(1, (note.length - t) / 0.06)
      const env = Math.max(0, Math.min(attack, release))
      const phase = 2 * Math.PI * note.frequency * t
      const wave = note.wave === 'triangle'
        ? (2 / Math.PI) * Math.asin(Math.sin(phase))
        : Math.sin(phase)
      samples[start + i] += wave * env * note.amplitude
    }
  }
  // Normalise then convert to 16-bit PCM WAV.
  let peak = 0
  for (const value of samples) peak = Math.max(peak, Math.abs(value))
  const gain = peak > 0 ? 0.85 / peak : 1
  const bytes = Buffer.alloc(44 + frames * 2)
  bytes.write('RIFF', 0)
  bytes.writeUInt32LE(36 + frames * 2, 4)
  bytes.write('WAVE', 8)
  bytes.write('fmt ', 12)
  bytes.writeUInt32LE(16, 16)
  bytes.writeUInt16LE(1, 20)
  bytes.writeUInt16LE(1, 22)
  bytes.writeUInt32LE(SAMPLE_RATE, 24)
  bytes.writeUInt32LE(SAMPLE_RATE * 2, 28)
  bytes.writeUInt16LE(2, 32)
  bytes.writeUInt16LE(16, 34)
  bytes.write('data', 36)
  bytes.writeUInt32LE(frames * 2, 40)
  for (let i = 0; i < frames; i += 1) {
    const value = Math.max(-1, Math.min(1, samples[i] * gain))
    bytes.writeInt16LE(Math.round(value * 32767), 44 + i * 2)
  }
  return { name: `${id}.wav`, bytes }
}

const tones = [
  // A classic two-tone chime, three repeats.
  tone('ulife_chime', [
    { start: 0.0, length: 0.22, frequency: 880, amplitude: 0.6 },
    { start: 0.18, length: 0.3, frequency: 1174.7, amplitude: 0.55 },
    { start: 0.6, length: 0.22, frequency: 880, amplitude: 0.6 },
    { start: 0.78, length: 0.3, frequency: 1174.7, amplitude: 0.55 },
    { start: 1.2, length: 0.22, frequency: 880, amplitude: 0.6 },
    { start: 1.38, length: 0.45, frequency: 1174.7, amplitude: 0.5 },
  ], 2.1),
  // A brighter bell: a struck metal bell with two partials.
  tone('ulife_bell', [
    { start: 0.0, length: 0.9, frequency: 1046.5, amplitude: 0.5 },
    { start: 0.0, length: 0.9, frequency: 1567.98, amplitude: 0.22 },
    { start: 0.5, length: 0.9, frequency: 1318.5, amplitude: 0.42 },
    { start: 0.5, length: 0.9, frequency: 1975.5, amplitude: 0.18 },
  ], 1.6),
  // A persistent alarm: alternating urgent pulses, long enough to wake a sleeper.
  tone('ulife_alarm', [
    ...Array.from({ length: 6 }, (_, i) => ({ start: i * 0.42, length: 0.2, frequency: i % 2 ? 988 : 740, amplitude: 0.7, wave: 'triangle' })),
  ], 2.7),
  // A single soft confirmation tick for notifications.
  tone('ulife_notification', [
    { start: 0.0, length: 0.16, frequency: 1318.5, amplitude: 0.5 },
    { start: 0.1, length: 0.2, frequency: 1760, amplitude: 0.35 },
  ], 0.45),
]

mkdirSync(RAW_DIR, { recursive: true })
mkdirSync(WEB_DIR, { recursive: true })
for (const file of tones) {
  writeFileSync(resolve(RAW_DIR, file.name), file.bytes)
  writeFileSync(resolve(WEB_DIR, file.name), file.bytes)
  console.log(`wrote ${file.name} (${file.bytes.length} bytes)`)
}
